'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const {profile,privateKey}=require('../test/fixtures.cjs');
const {_electron:electron}=require('playwright');
test('desktop lifecycle: translations, profiles, preferences and redacted reports', {timeout:90000},async()=>{
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'pocketsocket-ui-'));
  const env={...process.env,CI:'true',POCKET_TEST_DIR:path.join(temp,'userdata')};delete env.ELECTRON_RUN_AS_NODE;
  const args=['--hidden',...(process.platform==='linux'?['--no-sandbox']:[])];
  const desktop=await electron.launch(process.env.POCKET_TEST_EXECUTABLE?{executablePath:process.env.POCKET_TEST_EXECUTABLE,args,env,timeout:45000}:{args:[path.resolve(__dirname,'..'),...args],env,timeout:45000});
  try{
    const page=await desktop.firstWindow();const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.locator('#apps input').first().waitFor();
    if(await page.locator('#welcome').isVisible())await page.locator('#welcome-start').click();
    assert.equal(await page.evaluate(()=>typeof window.require),'undefined');
    await page.locator('#quick-language').selectOption('en');
    await page.waitForFunction(()=>document.getElementById('connect-label').textContent==='Connect');
    await page.locator('#quick-language').selectOption('tr');
    await page.waitForFunction(()=>document.getElementById('connect-label').textContent==='Bağlan');
    await page.locator('#quick-language').selectOption('en');
    await page.waitForFunction(()=>document.getElementById('connect-label').textContent==='Connect');
    assert.equal(await page.locator('#connect').isDisabled(),true);
    await page.locator('[data-show="settings"]').click();
    await page.locator('#theme').selectOption('dark');
    await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark');
    await page.locator('#remember').uncheck();
    await page.waitForFunction(()=>!document.getElementById('remember').checked);
    await page.locator('#theme').selectOption('light');
    await page.locator('[data-show="connect"]').click();
    await page.locator('#mode').selectOption('dns');
    await page.waitForFunction(()=>!document.getElementById('connect').disabled);
    await page.locator('#mode').selectOption('tunnel');
    await page.waitForFunction(()=>document.getElementById('connect').disabled);
    const filename=path.join(temp,'test-profile.conf');await fs.writeFile(filename,profile,{mode:0o600});
    await desktop.evaluate(({dialog},filename)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[filename]})},filename);
    await page.locator('#import').click();
    await page.waitForFunction(()=>document.getElementById('profile-select').selectedOptions[0]?.textContent.includes('test-profile.conf'));
    assert.equal(await page.locator('#connect').isEnabled(),true);
    const imported=await page.evaluate(()=>window.pocket.initial());
    assert.equal(imported.ok,true);assert(!JSON.stringify(imported).includes(privateKey));assert.equal(imported.value.state.hasSession,false);
    await fs.writeFile(filename,profile+'\n[Peer]\n');await page.locator('#import').click();
    await page.waitForFunction(()=>document.getElementById('toast').textContent.includes('standard'));
    assert.equal((await page.evaluate(()=>window.pocket.initial())).value.profiles.length,1);
    await page.locator('#profile-delete').click();await page.waitForFunction(()=>document.getElementById('profile-select').value==='');
    await page.locator('#proxy-open').click();await page.locator('#proxy-form [name="password"]').fill('private-proxy-password');await page.locator('#proxy-form [type="submit"]').click();
    await page.waitForFunction(()=>document.getElementById('profile-select').selectedOptions[0]?.textContent.includes('SOCKS5'));
    assert(!(JSON.stringify(await page.evaluate(()=>window.pocket.initial()))).includes('private-proxy-password'));
    await page.locator('#profile-delete').click();await page.waitForFunction(()=>document.getElementById('profile-select').value==='');
    await page.locator('#app-search').fill('Chrome');await page.locator('#apps input').first().check();
    await page.waitForFunction(()=>!document.getElementById('browser-warning').classList.contains('hidden'));
    await page.locator('#app-search').fill('');
    const report=path.join(temp,'report.json');await desktop.evaluate(({dialog},filename)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:filename})},report);
    await page.locator('[data-show="help"]').click();await page.locator('#report').click();
    await page.waitForFunction(()=>document.getElementById('toast').textContent.includes('support report'));
    const text=await fs.readFile(report,'utf8');assert(!text.includes(privateKey));assert(!text.includes('private-proxy-password'));assert(!text.includes('test-profile.conf'));
    await page.locator('[data-show="settings"]').click();await page.locator('#reset').click();
    await page.locator('[data-show="connect"]').click();
    assert.deepEqual(errors,[]);await fs.mkdir('.build',{recursive:true});
    // A hidden packaged Linux window can have no compositor frame under Xvfb.
    // Only disposable CI may reveal it; local test runs stay hidden.
    if(process.platform==='linux'&&process.env.GITHUB_ACTIONS==='true')await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].showInactive());
    await page.screenshot({path:'.build/desktop.png',fullPage:true});
  }finally{await desktop.close();await fs.rm(temp,{recursive:true,force:true})}
});
